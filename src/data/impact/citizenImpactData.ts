export function getCitizenImpactForRecord(recordIdOrSlug: string): CitizenImpactViewModel | undefined {
  if (!recordIdOrSlug) return undefined;
  const slug = recordIdOrSlug.toLowerCase().trim();
  
  if (CITIZEN_IMPACT_PILOT_REGISTRY[slug]) {
    return CITIZEN_IMPACT_PILOT_REGISTRY[slug];
  }

  // Fallback slug matching
  for (const [key, value] of Object.entries(CITIZEN_IMPACT_PILOT_REGISTRY)) {
    if (slug.includes(key) || key.includes(slug)) {
      return value;
    }
  }

  return undefined;
}
